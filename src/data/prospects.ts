type EventTuple = [kind: ContactEvent['kind'], text: string, date: string]

function history(prospectId: string, events: EventTuple[]): ContactEvent[] {
  return events.map(([kind, text, date], i) => ({ id: `${prospectId}-e${i + 1}`, kind, text, date }))
}

function notes(prospectId: string, items: [text: string, date: string][]): ProspectNote[] {
  return items.map(([text, date], i) => ({ id: `${prospectId}-n${i + 1}`, text, date }))
}

